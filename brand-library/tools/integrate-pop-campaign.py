from pathlib import Path
import json,os,zipfile,hashlib,shutil

ROOT=Path(__file__).resolve().parents[1];EXP=ROOT.parent/"openline-brand-expansion"
WORK=EXP/"campaign-voice-ten-v2";PUB=ROOT/"public";DEST=PUB/"library/campaign-voice-ten-v2"
